#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PROXY_PATH = path.join(ROOT, 'deployment/vercel-source-bridge/api/proxy.js');
const SNAPSHOT_PATH = path.join(ROOT, 'site-v15/data/helix-root.json');
const RECEIPT_PATH = path.join(ROOT, 'site-v15/data/v21-runtime-stars-reconciliation.json');

const sha256 = (value) => createHash('sha256').update(value).digest('hex');

const snapshotText = await readFile(SNAPSHOT_PATH, 'utf8');
const snapshot = JSON.parse(snapshotText);
const companyCount = Array.isArray(snapshot.companies) ? snapshot.companies.length : 0;
const helixCommit = String(snapshot?.source?.root_ref ?? '');
if (!Number.isInteger(companyCount) || companyCount < 1) {
  throw new Error('V21 runtime star reconciliation requires a non-empty Helix projection');
}
if (!/^[a-f0-9]{40}$/.test(helixCommit)) {
  throw new Error('V21 runtime star reconciliation requires an immutable Helix commit');
}

const source = await readFile(PROXY_PATH, 'utf8');
let next = source;

const generator = `function runtimeStarPositionCss(count) {
  if (!Number.isInteger(count) || count < 1) {
    throw new Error('runtime star projection requires a positive company count');
  }
  const rings = [];
  let remaining = count;
  let ring = 0;
  while (remaining > 0) {
    const capacity = 12 + ring * 10;
    const take = Math.min(remaining, capacity);
    rings.push(take);
    remaining -= take;
    ring += 1;
  }
  const rules = [
    '/* AUTO-GENERATED by V21 runtime projection — no client script */',
    \`/* \${count} governed company stars */\`,
  ];
  let index = 0;
  for (let ringIndex = 0; ringIndex < rings.length; ringIndex += 1) {
    const ringCount = rings[ringIndex];
    const radius = rings.length === 1
      ? 31
      : 16 + (31 * ringIndex) / (rings.length - 1);
    const offset = -Math.PI / 2 + (ringIndex % 2 === 0 ? 0 : Math.PI / ringCount);
    for (let item = 0; item < ringCount; item += 1) {
      const angle = offset + (Math.PI * 2 * item) / ringCount;
      const left = 50 + radius * Math.cos(angle);
      const top = 50 + radius * Math.sin(angle);
      rules.push(
        \`.atlas-star.star-p\${index}{left:\${left.toFixed(3)}%;top:\${top.toFixed(3)}%}\`,
      );
      index += 1;
    }
  }
  return \`\${rules.join('\\n')}\\n\`;
}

`;

if (!next.includes('function runtimeStarPositionCss(count) {')) {
  const anchor = 'async function verifyDeployment(res) {';
  if (!next.includes(anchor)) throw new Error('proxy.js: V21 verifier anchor missing');
  next = next.replace(anchor, `${generator}${anchor}`);
}

const staticVerifyBlock = `    const stars = await fetchSource('assets/helix-atlas.stars.css');
    const starsText = stars.body.toString('utf8');
    const starsOk = stars.response.ok && starsText.includes('.atlas-star.star-p0{') && starsText.includes(\`.atlas-star.star-p\${Math.max(0, (projection?.company_count || 1) - 1)}{\`);
    pass = pass && starsOk;
    files.push({ path: 'assets/helix-atlas.stars.css', status: stars.response.status, bytes: stars.body.length, sha256: stars.sha256, expected: 'generated multi-ring star positions', ok: starsOk });`;
const dynamicVerifyBlock = `    const starsText = projection ? runtimeStarPositionCss(projection.company_count) : '';
    const starsBody = Buffer.from(starsText);
    const starsOk = Boolean(projection) && starsText.includes('.atlas-star.star-p0{') &&
      starsText.includes(\`.atlas-star.star-p\${Math.max(0, (projection?.company_count || 1) - 1)}{\`);
    pass = pass && starsOk;
    files.push({
      path: 'assets/helix-atlas.stars.css',
      status: projection ? 200 : 503,
      bytes: starsBody.length,
      sha256: sha256(starsBody),
      expected: 'runtime-generated multi-ring star positions from pinned Helix projection',
      ok: starsOk,
    });`;
if (next.includes(staticVerifyBlock)) {
  next = next.replace(staticVerifyBlock, dynamicVerifyBlock);
} else if (!next.includes('runtime-generated multi-ring star positions from pinned Helix projection')) {
  throw new Error('proxy.js: historical V21 static-star verifier block missing');
}

const needsAnchor = `function needsProjection(filePath) {
  return filePath === 'atlas/index.html' ||`;
const needsReplacement = `function needsProjection(filePath) {
  return filePath === 'assets/helix-atlas.stars.css' ||
    filePath === 'atlas/index.html' ||`;
if (next.includes(needsAnchor)) {
  next = next.replace(needsAnchor, needsReplacement);
} else if (!next.includes("filePath === 'assets/helix-atlas.stars.css' ||")) {
  throw new Error('proxy.js: V21 projection routing anchor missing');
}

const dynamicAnchor = `async function dynamicResponse(filePath, projection) {
  if (filePath === 'atlas/index.html' || filePath === 'companies/index.html') {`;
const dynamicReplacement = `async function dynamicResponse(filePath, projection) {
  if (filePath === 'assets/helix-atlas.stars.css') {
    return {
      status: 200,
      type: TYPES['.css'],
      body: Buffer.from(runtimeStarPositionCss(projection.company_count)),
    };
  }
  if (filePath === 'atlas/index.html' || filePath === 'companies/index.html') {`;
if (next.includes(dynamicAnchor)) {
  next = next.replace(dynamicAnchor, dynamicReplacement);
} else if (!next.includes("filePath === 'assets/helix-atlas.stars.css'")) {
  throw new Error('proxy.js: V21 dynamic-response anchor missing');
}

if (next.includes("fetchSource('assets/helix-atlas.stars.css')")) {
  throw new Error('proxy.js: V21 verifier still depends on historical static star CSS');
}
if (!next.includes("filePath === 'assets/helix-atlas.stars.css' ||")) {
  throw new Error('proxy.js: V21 runtime star CSS is not projection-gated');
}
if (!next.includes("body: Buffer.from(runtimeStarPositionCss(projection.company_count))")) {
  throw new Error('proxy.js: V21 runtime star CSS route is missing');
}
if (!next.includes(`const HELIX_COMMIT = '${helixCommit}';`)) {
  throw new Error('proxy.js: V21 runtime Helix authority does not match fresh projection');
}

await writeFile(PROXY_PATH, next, 'utf8');
const receipt = {
  schema: 'glaciereq.v21-runtime-star-reconciliation.v1',
  status: 'PASS',
  authoritative_helix_commit: helixCommit,
  authoritative_company_tracks: companyCount,
  proxy_before_sha256: sha256(source),
  proxy_after_sha256: sha256(next),
  invariants: [
    'V21 star-position CSS is generated from the same immutable Helix projection used for company routes.',
    'The V21 verifier no longer asks a historical static site commit to contain positions for future company tracks.',
    'All governed company stars receive deterministic server-side CSS positions with no client JavaScript.',
    'Runtime ring radii remain bounded inside the constellation stage as the estate grows.',
  ],
};
await writeFile(RECEIPT_PATH, `${JSON.stringify(receipt, null, 2)}\n`, 'utf8');
console.log(JSON.stringify({
  status: 'PASS',
  authoritative_helix_commit: helixCommit,
  authoritative_company_tracks: companyCount,
  proxy_changed: next !== source,
  proxy_sha256: receipt.proxy_after_sha256,
}));
